/**
 * Авто-типограф. Один и тот же модуль используется на сборке (rehype-плагин)
 * и в админке для live-превью, поэтому картинка в редакторе = картинка на сайте.
 *
 * Работает только по текстовым узлам HTML: <code>, <pre>, <script>, <style>,
 * <textarea> и содержимое тегов с data-notypeset не трогаем никогда.
 *
 * Железное правило: типограф имеет право менять символ только на его месте.
 * Ни одно правило не вставляет пробел внутри слова и не добавляет цифр,
 * которых не было на входе. Это проверяет scripts/check-typeset.mjs на корпусе
 * всех строк сайта — см. docs/DESIGN_RULES.md.
 */

export type TypesetOptions = {
  /** Восстанавливает ё по словарю целых слов. */
  yo?: boolean;
  locale?: 'ru';
};

const NBSP = ' ';

/**
 * Ё восстанавливаем только по точному совпадению слова с учётом регистра.
 * Слова, где «е» может быть формой другого слова (все/ней/всего), в список
 * не входят: ошибка подстановки обходится дороже пропущенной буквы.
 */
const YO_MAP: Record<string, string> = {
  еще: 'ещё',
  ее: 'её',
  нее: 'неё',
  почем: 'почём',
  зачтет: 'зачтёт',
  прочтет: 'прочтёт',
  узнает: 'узнаёт',
  найден: 'найдён',
  жосткий: 'жёсткий',
  жосткость: 'жёсткость',
  жостко: 'жёстко',
  осел: 'осёл',
};

/** Сокращения с точками: неразрывные пробелы ставим строго между частями. */
const ABBREVIATIONS = ['и т. д.', 'и т. п.', 'т. д.', 'т. п.', 'т. е.', 'т. н.', 'л. с.', 'н. э.', 'в. э.'];

/**
 * Служебные слова, которые нельзя отрывать от следующего за ними слова.
 * Скобки вокруг списка — не декорация: replace читает их как отдельный
 * аргумент, и любой лишний захват сдвигает параметры callback.
 */
const SMALL_WORDS =
  '([а-яё]|из|из-под|до|по|от|за|над|под|при|про|без|через|между|насчёт|вокруг|около|тоже|также|или|если|чтобы|как|ведь|же|ли|бы|но|да|ну|вот|это|раз|два|три)';

/** Единицы, слипаемые с числом. */
const UNIT = '(?:%|‰|₽|\\$|€|£|грн\\.|тенге|руб\\.|мм|см|км|кг|мг|т\\.|с\\.|мин\\.|сек\\.|ч\\.|дн\\.|сут\\.|мес\\.|лет|год|года|КБ|МБ|ГБ|кБ|Мб|Gb|MB|pp|п\\.\\s?п\\.)';

export function typesetText(raw: string, options: TypesetOptions = {}): string {
  if (!raw || !raw.trim()) return raw;
  let t = raw.replace(/[\u00A0\u2007\u202F]/g, ' ').replace(/[ \t]{2,}/g, ' ');

  // Многоточие.
  t = t.replace(/\.{3,}/g, '…');

  // Кавычки-лапки → ёлочки. Работаем только по парам целиком, без вложенности.
  t = t.replace(/"([^"\n]+)"/g, '«$1»');
  t = t.replace(/„([^“\n]+)“/g, '«$1»');
  t = t.replace(/(^|[\s(\[])'([^\s'][^'\n]*?)'(?=[\s).,!?:;]|$)/g, '$1«$2»');

  // Тире: одиночный дефис между пробелами — всегда длинное тире.
  t = t.replace(/[ \t]{1,}[-–—]{1,2}[ \t]{1,}/g, ` ${DASH_EM} `);
  // Диапазоны чисел: 2024-2026, 10-15 %.
  t = t.replace(/(?<=\d)-(?=\d)/g, DASH_EN);

  // Ё по словарю целых слов.
  if (options.yo !== false) {
    t = t.replace(/[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*/g, (word) => {
      const mapped = YO_MAP[word.toLowerCase()];
      if (!mapped || mapped === word.toLowerCase()) return word;
      return word[0] === word[0].toUpperCase() ? capitalize(mapped) : mapped;
    });
  }

  // Неразрывные пробелы внутри сокращений («и т.д.» → «и т. д.» с NBSP).
  for (const abbr of ABBREVIATIONS) {
    const pattern = abbr
      .split(' ')
      .map((part) => part.replace(/\./g, '\\s*\\.\\s*'))
      .join('\\s+');
    t = t.replace(new RegExp(`\\b${pattern}\\b`, 'gi'), (match) =>
      match
        .replace(/(\.)\s+/g, `$1${NBSP}`)
        .replace(/\s+(\S\.)/g, `${NBSP}$1`),
    );
  }

  // Число и единица: 30 мин, 58 %, 4,2 млн ₽.
  t = t.replace(new RegExp(`(\\d)[ \\t]+(?=${UNIT}\\b)`, 'giu'), `$1${NBSP}`);
  t = t.replace(new RegExp(`(\\d)[ \\t]+(?=(?:млн|млрд|тыс\\.|тыс|экз\\.)\\b)`, 'giu'), `$1${NBSP}`);

  // Знак и номер: № 12, к. 3, п. 1 — не отрывать от цифры.
  t = t.replace(/(№|#|~|≈)\s+(?=\d)/g, `$1${NBSP}`);

  // Предлоги и союзы склеиваем со следующим словом, но только внутри строки:
  // в начале текста висячий однобуквенный союз остаётся как есть.
  t = t.replace(new RegExp(`(\\S)[ \\t]+${SMALL_WORDS}[ \\t]+(?=\\p{L})`, 'giu'), (_m, edge, word) =>
    `${edge} ${word}${NBSP}`,
  );
  t = t.replace(new RegExp(`^${SMALL_WORDS}[ \\t]+(?=\\p{L})`, 'giu'), (_m, word) => `${word}${NBSP}`);

  // Умножение: 2 x 3 / 2х3 → 2 × 3. Одиночную букву x не трогаем никогда.
  t = t.replace(/(\d)[ \t]*[xх](\d|[ \t]\d)/giu, (_m, a, b) => `${a} × ${b.replace(/^\s/, '')}`);

  // Тысячи: тонкий пробел в числах от пяти знаков. Года и четырёхзначные не трогаем.
  t = t.replace(/\b\d{5,}\b/g, (num) => num.replace(/\B(?=(\d{3})+(?!\d))/g, THIN));

  return t;
}

const DASH_EM = '—';
const DASH_EN = '–';
const THIN = ' ';

function capitalize(word: string) {
  return word.charAt(0).toUpperCase() + word.slice(1);
}

export const isSkippedTag = (tag: string) =>
  ['code', 'pre', 'script', 'style', 'textarea', 'svg', 'kbd', 'samp', 'var'].includes(tag);
